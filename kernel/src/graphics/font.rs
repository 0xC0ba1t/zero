/// Draw a single text character at (x, y) in pixel coordinates using
/// the given foreground and background colors.
pub fn draw_char(display: &mut dyn crate::graphics::display::Display, x: usize, y: usize, byte: u8, fg: u32, bg: u32) {
    let glyph = glyph(byte);
    for row in 0..CHAR_HEIGHT {
        let bits = glyph[row];
        for col in 0..CHAR_WIDTH {
            if (bits << col) & 0x80 != 0 {
                display.put_pixel(x + col, y + row, fg);
            } else if bg != 0 {
                display.put_pixel(x + col, y + row, bg);
            }
        }
    }
}

/// Draw a text string at (x, y) in pixel coordinates.
pub fn draw_text(display: &mut dyn crate::graphics::display::Display, x: usize, y: usize, text: &str, fg: u32, bg: u32) {
    for (index, byte) in text.bytes().enumerate() {
        draw_char(display, x + index * CHAR_WIDTH, y, byte, fg, bg);
    }
}

/// Draw a single block character at character-grid position (col, row),
/// scaling to pixel coordinates with a 2px gap between cells.
pub fn draw_block_char(display: &mut dyn crate::graphics::display::Display, col: usize, row: usize, byte: u8, fg: u32, bg: u32) {
    let gap = 2;
    let px = col * (CHAR_WIDTH + gap);
    let py = row * (CHAR_HEIGHT + gap);
    draw_char(display, px, py, byte, fg, bg);
}
